PDFS = {key: next((PROCESSOR / key).glob("*_cleaned.pdf")) for key in {key for key, _, _ in CUSTOM_CROPS.values()}}

def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, relative in AUTO_CROPS.items():
        source = PROCESSOR / relative
        if not source.exists():
            raise FileNotFoundError(source)
        shutil.copy2(source, OUT / name)
    for name, (key, page_index, box) in CUSTOM_CROPS.items():
        document = fitz.open(PDFS[key])
        try:
            pix = document[page_index].get_pixmap(matrix=fitz.Matrix(2, 2), alpha=False)
            image = Image.frombytes("RGB", (pix.width, pix.height), pix.samples)
            scaled = tuple(int(value * 2) for value in box)
            crop = ImageOps.expand(image.crop(scaled), border=12, fill="white")
            crop.save(OUT / name, optimize=True)
        finally:
            document.close()
    print("\n".join(sorted(path.name for path in OUT.glob("*.png"))))

if __name__ == "__main__":
    main()
