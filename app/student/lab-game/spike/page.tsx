"use client";

import React, { useState } from "react";
import dynamic from "next/dynamic";
import Link from "next/link";
import { ArrowLeft, Magnet, MousePointerClick, CheckCircle2, RotateCcw } from "lucide-react";

// Three.js must never run on the server — load the scene client-only.
const LabScene = dynamic(() => import("./LabScene"), {
  ssr: false,
  loading: () => (
    <div className="flex h-full w-full items-center justify-center text-sm font-medium text-muted-foreground">
      Loading lab…
    </div>
  ),
});

/**
 * A practical, modelled as data. In the real feature this comes from the DB and
 * can be generated by Gemini. The 3D scene emits events; the step machine here
 * decides what instruction to show next.
 */
const STEPS = [
  {
    icon: MousePointerClick,
    title: "Look around the lab",
    body: "Drag to orbit the camera. When you're ready, click the glowing magnet on the right to pick it up.",
    advanceOn: "grabbed" as const,
  },
  {
    icon: Magnet,
    title: "Attract the iron filings",
    body: "Move your cursor over the grey/brown mixture on the table. The iron filings are magnetic — they'll jump to the magnet.",
    advanceOn: "collected" as const,
  },
  {
    icon: CheckCircle2,
    title: "Separation complete",
    body: "The iron filings are now on the magnet, and only the sand is left on the table. That's the whole practical — separating a mixture by magnetism.",
    advanceOn: null,
  },
];

export default function LabSpikePage() {
  const [stepIndex, setStepIndex] = useState(0);
  const [sceneKey, setSceneKey] = useState(0); // bump to reset the scene
  const step = STEPS[stepIndex];
  const Icon = step.icon;

  const handleEvent = (e: "grabbed" | "collected") => {
    if (step.advanceOn === e) setStepIndex((i) => Math.min(i + 1, STEPS.length - 1));
  };

  const reset = () => {
    setStepIndex(0);
    setSceneKey((k) => k + 1);
  };

  return (
    <div className="relative h-[100dvh] w-full overflow-hidden bg-[#dfe6ee]">
      {/* 3D canvas fills the screen */}
      <div className="absolute inset-0">
        <LabScene key={sceneKey} onEvent={handleEvent} />
      </div>

      {/* Top bar */}
      <div className="pointer-events-none absolute inset-x-0 top-0 flex items-center justify-between p-4">
        <Link
          href="/student/lab-game"
          className="pointer-events-auto inline-flex items-center gap-2 rounded-full bg-black/70 px-4 py-2 text-sm font-semibold text-white backdrop-blur transition hover:bg-black/80"
        >
          <ArrowLeft size={16} /> Back
        </Link>
        <span className="pointer-events-none rounded-full bg-black/60 px-4 py-2 text-xs font-bold uppercase tracking-widest text-white/90 backdrop-blur">
          Prototype · Iron &amp; Sand
        </span>
      </div>

      {/* Guidance card */}
      <div className="pointer-events-none absolute inset-x-0 bottom-0 flex justify-center p-4 sm:p-6">
        <div className="pointer-events-auto w-full max-w-md rounded-3xl border border-white/40 bg-white/85 p-5 shadow-2xl backdrop-blur-md">
          {/* Step dots */}
          <div className="mb-3 flex items-center gap-1.5">
            {STEPS.map((_, i) => (
              <div
                key={i}
                className={`h-1.5 flex-1 rounded-full transition-colors ${
                  i <= stepIndex ? "bg-emerald-500" : "bg-black/10"
                }`}
              />
            ))}
          </div>

          <div className="flex items-start gap-3">
            <div
              className={`flex h-10 w-10 shrink-0 items-center justify-center rounded-2xl ${
                step.advanceOn === null ? "bg-emerald-500 text-white" : "bg-blue-500/15 text-blue-600"
              }`}
            >
              <Icon size={20} />
            </div>
            <div className="min-w-0">
              <p className="text-[11px] font-bold uppercase tracking-widest text-black/40">
                Step {stepIndex + 1} of {STEPS.length}
              </p>
              <h2 className="text-lg font-black leading-tight text-black">{step.title}</h2>
              <p className="mt-1 text-sm leading-snug text-black/70">{step.body}</p>
            </div>
          </div>

          {step.advanceOn === null && (
            <button
              onClick={reset}
              className="mt-4 inline-flex w-full items-center justify-center gap-2 rounded-2xl bg-black px-4 py-2.5 text-sm font-bold text-white transition hover:bg-black/85"
            >
              <RotateCcw size={16} /> Run it again
            </button>
          )}
        </div>
      </div>
    </div>
  );
}
